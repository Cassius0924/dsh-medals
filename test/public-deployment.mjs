import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {CHALLENGES} from '../src/challenges.js';

const publicUrl='https://dsh.cassdev.com';
const log=execFileSync('journalctl',['-u','dsh.service','-b','--no-pager','-n','7000'],{maxBuffer:8*1024*1024,encoding:'utf8'});
const launch=[...log.matchAll(/https?:\/\/[^\s]+\?token=[A-Za-z0-9_-]+/g)].map(m=>new URL(m[0])).filter(u=>u.origin==='http://127.0.0.1:3080').at(-1);
assert(launch,'Live DSH authentication launch URL must exist');
const exchange=await fetch(publicUrl+launch.pathname+launch.search,{redirect:'manual',signal:AbortSignal.timeout(15000)});
assert.equal(exchange.status,303);
const cookie=exchange.headers.getSetCookie().map(s=>s.split(';')[0]).join('; ');
assert(cookie);
const request=path=>fetch(publicUrl+path,{headers:{cookie},signal:AbortSignal.timeout(120000)});
const response=await request('/api/dsh-medals/status');
assert.equal(response.status,200);
const status=await response.json();
assert.equal(status.complete,true);
assert.equal(status.challenges.rules.length,22);
assert.deepEqual(status.challenges.rules,CHALLENGES,'Public host must serve the current challenge artwork configuration');
const backup=(await readFile(new URL('../evidence/preview-backup-location.txt',import.meta.url),'utf8')).trim();
const previous=JSON.parse(await readFile(backup+'/ledger.json','utf8'));
for(const award of previous.challenges.awards)assert.deepEqual(status.challenges.awards.find(a=>a.id===award.id),award,'Earned records must retain their dates, serials and acknowledgement state');
const asset=await request('/api/dsh-medals/ui/medal-renderer.js');
assert.equal(asset.status,200);
const sha=data=>createHash('sha256').update(data).digest('hex');
const rendererSha256=sha(Buffer.from(await asset.arrayBuffer()));
assert.equal(rendererSha256,sha(await readFile(new URL('../lib/ui/medal-renderer.js',import.meta.url))));
const anonymous=await fetch(publicUrl+'/api/dsh-medals/status',{signal:AbortSignal.timeout(15000)});
assert.equal(anonymous.status,401);
const result={passed:true,publicUrl,authenticatedStatus:response.status,anonymousStatus:anonymous.status,rendererSha256,total:status.total,challengeKinds:status.challenges.rules.length,challengeAwards:status.challenges.awards.length,earnedRecordsPreserved:true};
await writeFile(new URL('../evidence/public-deployment.json',import.meta.url),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
