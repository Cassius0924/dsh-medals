export function normalizeLocale(value) {
  return /^zh(?:-|$)/i.test(String(value)) ? 'zh' : 'en';
}

export function createI18n(initialLocale = 'en') {
  let locale = normalizeLocale(initialLocale);
  const t = (key, params = {}) => {
    const pluralKey = Object.hasOwn(params, 'count') ? key + '.' + new Intl.PluralRules(locale).select(Number(params.count)) : key;
    const text = dictionaries[locale][pluralKey] ?? dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(params, name) ? String(params[name]) : match);
  };
  return {
    t,
    get locale() { return locale; },
    setLocale(value) { locale = normalizeLocale(value); },
    number(value, options) { return new Intl.NumberFormat(locale === 'zh' ? 'zh-CN' : 'en-US', options).format(value); },
    date(value) {
      if (!/^\d{4}-\d{2}-\d{2}$/.test(value ?? '')) return String(value ?? '');
      // Award dates are calendar dates in the ledger's fixed timezone, not instants.
      if (locale === 'zh') return value;
      return new Intl.DateTimeFormat('en-US', {dateStyle: 'medium', timeZone: 'UTC'}).format(new Date(value + 'T12:00:00Z'));
    },
    medalName(rule) {
      if (locale === 'zh') return rule.name;
      if (dictionaries.en['medal.' + rule.id]) return t('medal.' + rule.id);
      if (rule.series === 'daily') return t('dailyName', {amount: rule.target / 1e6});
      if (rule.series === 'weekly') return rule.perfect ? t('perfectWeekName') : t('weekDaysName', {days: rule.target});
      if (rule.series === 'monthly') return rule.perfect ? t('perfectMonthName') : t('monthDaysName', {days: rule.target});
      if (rule.series === 'days') return t('lifetimeDaysName', {days: rule.target});
      if (rule.series === 'tokens') return t('lifetimeTokensName', {amount: rule.number});
      return rule.name;
    }
  };
}
