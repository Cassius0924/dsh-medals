"""Extract the bundled Baskervville numeral outlines for the 3D and 2D renderers."""
from pathlib import Path
import json
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen

root = Path(__file__).resolve().parent.parent
font = TTFont(root / 'vendor/numerals/serif-source.ttf')
glyphs = font.getGlyphSet(location={'wght': 500})
cmap = font.getBestCmap()
lining = {}
substitutions = font['GSUB'].table
for feature in substitutions.FeatureList.FeatureRecord:
    if feature.FeatureTag == 'lnum':
        for index in feature.Feature.LookupListIndex:
            for table in substitutions.LookupList.Lookup[index].SubTable:
                lining.update(table.mapping)

class OutlinePen(BasePen):
    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.commands = []
    def _moveTo(self, p): self.commands.append(['M', *p])
    def _lineTo(self, p): self.commands.append(['L', *p])
    def _curveToOne(self, a, b, c): self.commands.append(['C', *a, *b, *c])
    def _qCurveToOne(self, a, b): self.commands.append(['Q', *a, *b])
    def _closePath(self): self.commands.append(['Z'])
    def _endPath(self): pass

outlines = {}
for char in '0123456789M':
    name = cmap[ord(char)]
    glyph = glyphs[lining.get(name, name)]
    pen = OutlinePen(glyphs)
    glyph.draw(pen)
    outlines[char] = {'advance': glyph.width, 'commands': pen.commands}
(root / 'src/numeral-glyphs.js').write_text(
    '// Baskervville lining numerals, weight 500; see vendor/numerals/LICENSE. Generated by scripts/build-numerals.py.\n'
    + 'export const NUMERAL_GLYPHS=' + json.dumps(outlines, separators=(',', ':')) + ';\n'
)
